def format_items(value):

    try:

        if pd.isna(value):

            return ""

        text = str(value).strip()

        if text.startswith("[") and text.endswith("]"):

            try:

                parsed = json.loads(
                    text.replace("'", '"')
                )

                if isinstance(parsed, list):

                    return ", ".join(
                        str(x) for x in parsed
                    )

            except Exception:

                text = (
                    text
                    .replace("[", "")
                    .replace("]", "")
                    .replace("'", "")
                    .replace('"', "")
                )

                return text

        return text

    except Exception:

        return str(value)


